import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { DEFAULT_SETTINGS, dateRange, timeLabel, normalizeExcludedApps, validateSettings, errorKey } from '../src/features/clipboard-history/core.js';
import { createClipboardRuntime, copySensitiveText } from '../src/platform/clipboard-runtime.js';
import template from '../src/features/clipboard-history/template.js';
import { LAZY_TOOL_SPECS } from '../src/features/lazy-tools.js';

assert.equal(LAZY_TOOL_SPECS['clipboard-history'].overlayId, 'clipboardHistoryOverlay');
assert.equal(LAZY_TOOL_SPECS['clipboard-history'].init, 'initClipboardHistoryTool');
assert.match(template, /tool-page-v2-topbar/);
const ids = [...template.matchAll(/\bid="([^"]+)"/g)].map(match => match[1]);
assert.equal(ids.length, new Set(ids).size);
for (const id of ['clipboardToggle', 'clipboardList', 'clipboardPreview', 'clipboardHistoryDialog', 'clipboardSelectAll']) assert.ok(ids.includes(id));
assert.ok(validateSettings({ ...DEFAULT_SETTINGS }));
assert.ok(!validateSettings({ ...DEFAULT_SETTINGS, retentionDays: 0 }));
assert.ok(!validateSettings({ ...DEFAULT_SETTINGS, maxMegabytes: Infinity }));
assert.ok(!validateSettings({ ...DEFAULT_SETTINGS, excludedApps: ['C:\\private.exe'] }));
assert.deepEqual(normalizeExcludedApps('App.EXE\n app.exe, vault.exe'), ['app.exe', 'vault.exe']);
assert.deepEqual(dateRange(''), {});
const day = new Date(2026, 8, 20, 14, 23, 45);
assert.equal(dateRange('today', day).from, new Date(2026, 8, 20).getTime());
assert.match(timeLabel(Date.UTC(2026, 8, 20, 6, 23, 45, 123), 'en', true, 480), /14:23:45\.123.*UTC\+08:00/);
assert.equal(errorKey('clipboard:record-damaged'), 'recordDamaged');
assert.equal(errorKey('sensitive arbitrary native error'), 'operationFailed');
await assert.rejects(createClipboardRuntime().request({ action: 'start' }), /desktop-only/);
let requests = [], subscriptions = 0;
const tauri = Promise.resolve({ invoke: async (command, payload) => { requests.push({ command, payload }); return { enabled: true }; } });
const runtime = createClipboardRuntime({ isTauri: true, tauri, events: Promise.resolve({ listen: async (name, cb) => { assert.equal(name, 'clipboard-history-changed'); subscriptions++; cb(); return () => subscriptions--; } }) });
assert.deepEqual(await runtime.request({ action: 'start' }), { enabled: true });
let called = 0; const unlisten = await runtime.subscribe(() => called++); assert.equal(called, 1); unlisten(); assert.equal(subscriptions, 0);
await copySensitiveText('synthetic password', { isTauri: true, tauri });
assert.equal(requests.at(-1).command, 'copy_sensitive_text');
let plain = ''; await copySensitiveText('browser sample', { clipboard: { writeText: value => { plain = value; } } }); assert.equal(plain, 'browser sample');
const zh = JSON.parse(await readFile(new URL('../src/locales/zh.json', import.meta.url), 'utf8')).home.clipboardHistory;
const en = JSON.parse(await readFile(new URL('../src/locales/en.json', import.meta.url), 'utf8')).home.clipboardHistory;
assert.deepEqual(Object.keys(zh).sort(), Object.keys(en).sort());
for (const match of template.matchAll(/home\.clipboardHistory\.([A-Za-z]+)/g)) assert.ok(zh[match[1]], match[1]);
for (const state of ['desktopOnly', 'loading', 'noMatches', 'waiting', 'empty']) for (const suffix of ['Title', 'Description']) assert.ok(zh[state + suffix]);
const source = await readFile(new URL('../src/features/clipboard-history/controller.js', import.meta.url), 'utf8');
assert.doesNotMatch(source, /innerHTML\s*=|from ['"]@tauri-apps/);
assert.match(source, /owner\.use\(await runtime\.subscribe/);
assert.match(source, /control\?\.dispose/);
const password = await readFile(new URL('../src/features/password-generator/tool.js', import.meta.url), 'utf8');
assert.match(password, /copySensitiveText\(password, \{ isTauri \}\)/);
const runner = await readFile(new URL('../src-tauri/src/native_runtime/runner.rs', import.meta.url), 'utf8');
assert.match(runner, /RunEvent::ExitRequested/);
assert.match(runner, /clipboard_history::on_exit_requested/);
const store = await readFile(new URL('../src-tauri/src/clipboard_history/store.rs', import.meta.url), 'utf8');
assert.doesNotMatch(store.slice(store.indexOf('pub fn detail'), store.indexOf('pub fn page')), /\.exists\(|metadata\(/);
console.log('Clipboard history core, native bridge, privacy-copy and public UI contracts passed.');
